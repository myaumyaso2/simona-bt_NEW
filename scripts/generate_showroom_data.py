def make_list(items, title_pool):
    res = []
    pool_len = len(title_pool)
    for idx, item in enumerate(items):
        t, st = title_pool[idx % pool_len]
        num_str = f"{idx + 1:02d}"
        res.append({
            "id": f"photo-{idx + 1}",
            "number": num_str,
            "title": t,
            "subtitle": st,
            "photo": item["file"]
        })
    return res

