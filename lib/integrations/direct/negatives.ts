/**
 * Проверяет поисковый запрос на наличие стоп-слов из словаря
 */
export function isNegativeQuery(query: string): boolean {
  const normalized = query.toLowerCase().trim();
  return CORE_NEGATIVE_KEYWORDS.some((kw) => {
    const regex = new RegExp(`(^|\\s|\\W)${kw.replace('/', '\\/')}(\\s|\\W|$)`, 'i');
    return regex.test(normalized);
  });
}
